#!/usr/bin/env python3
"""Download every pinned third-party library into vendor/ and regenerate
js/vendor-manifest.js (CDN URL + local fallback path + SRI hash for each file).

Usage:  python3 scripts/fetch-vendor.py
Edit vendor/manifest.json to change versions, then re-run.
"""
import base64, hashlib, json, pathlib, sys, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
manifest = json.loads((ROOT / "vendor/manifest.json").read_text())
base = manifest["cdnBase"]


def fetch(url, dest):
    print(f"  {url}\n    -> {dest.relative_to(ROOT)}")
    req = urllib.request.Request(url, headers={"User-Agent": "fetch-vendor"})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = r.read()
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(data)
    return "sha384-" + base64.b64encode(hashlib.sha384(data).digest()).decode()


out = []
for lib in manifest["libraries"]:
    print(f"{lib['name']}@{lib['version']}")
    prefix = f"{base}{lib['package']}@{lib['version']}/"
    sri = fetch(prefix + lib["file"], ROOT / lib["local"])
    for extra in lib.get("extras", []):
        fetch(prefix + extra["file"], ROOT / extra["local"])
    out.append({"name": lib["name"], "type": lib["type"], "cdn": prefix + lib["file"],
                "local": lib["local"], "integrity": sri, "global": lib.get("global")})

js = ("// GENERATED by scripts/fetch-vendor.py — do not edit by hand.\n"
      "window.VENDOR_LIBS = " + json.dumps(out, indent=2) + ";\n")
(ROOT / "js/vendor-manifest.js").write_text(js)
print("Wrote js/vendor-manifest.js")
